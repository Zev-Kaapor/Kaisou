// All the news of a title, one under the other, with back at the top
@Composable
fun NewsScreen(onBack: () -> Unit, modifier: Modifier = Modifier, viewModel: NewsViewModel = viewModel()) {
    val dimens = KaisouTheme.dimens
    val state by viewModel.state.collectAsState()

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background)
            .windowInsetsPadding(WindowInsets.safeDrawing.only(WindowInsetsSides.Top + WindowInsetsSides.Horizontal))
    ) {
        Row(
            modifier = Modifier.fillMaxWidth().padding(horizontal = dimens.spaceSmall, vertical = dimens.spaceExtraSmall),
            verticalAlignment = Alignment.CenterVertically
        ) {
            HeaderAction(icon = KaisouIcons.Back, contentDescription = stringResource(R.string.cd_back), onClick = onBack)
            Text(
                text = stringResource(R.string.title_section_news),
                style = MaterialTheme.typography.titleMedium,
                color = MaterialTheme.colorScheme.onBackground,
                modifier = Modifier.padding(horizontal = dimens.spaceSmall)
            )
        }
        LazyColumn(
            modifier = Modifier.fillMaxSize(),
            contentPadding = PaddingValues(horizontal = dimens.screenPadding, vertical = dimens.spaceSmall),
            verticalArrangement = Arrangement.spacedBy(dimens.spaceSmall)
        ) {
            when (val news = state) {
                is Load.Done -> {
                    if (news.value.isEmpty()) {
                        item(key = "news-empty") {
                            Text(
                                text = stringResource(R.string.title_news_empty),
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                textAlign = TextAlign.Center,
                                modifier = Modifier.fillMaxWidth().padding(dimens.screenPadding)
                            )
                        }
                    }
                    items(news.value.distinctBy { it.url }, key = { it.url }) { NewsCard(it) }
                }
                is Load.Failed -> item(key = "news-error") { DetailsError(onRetry = viewModel::load) }
                else -> item(key = "news-loading") { DetailsSkeleton() }
            }
        }
    }
}
